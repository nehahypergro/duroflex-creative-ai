'use strict';
// Keep the shared theme in the two already-served CSS bundles. This also supports
// the standalone admin server without adding a Studio dependency or restarting jobs.
// Only the text between the BEGIN and END markers is replaced (8 Nov 2026): styles added
// after the theme block stay in place and keep their cascade order.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const marker = '/* BEGIN SHARED VISUAL THEME — generated by scripts/sync-visual-theme.js */';
const endMarker = '/* END SHARED VISUAL THEME */';
const theme = fs.readFileSync(path.join(root, 'public/creative-ai/visual-theme.css'), 'utf8');
function sync(current) {
  const block = marker + '\n' + theme.replace(/\n*$/, '\n') + endMarker + '\n';
  if (!current.includes(marker)) return current.trimEnd() + '\n\n' + block;
  const start = current.indexOf(marker), endAt = current.indexOf(endMarker, start);
  // Older files without an END marker: the generated theme is exactly what follows BEGIN.
  const tail = endAt >= 0 ? current.slice(endAt + endMarker.length).replace(/^\n+/, '') : (current.slice(start + marker.length + 1).startsWith(theme) ? current.slice(start + marker.length + 1 + theme.length).replace(/^\n+/, '') : '');
  if (endAt < 0 && current.slice(start + marker.length + 1).trim() && !current.slice(start + marker.length + 1).startsWith(theme)) throw new Error('Cannot find where the shared theme ends; add "' + endMarker + '" after it before syncing.');
  return current.slice(0, start).trimEnd() + '\n\n' + block + (tail ? '\n' + tail : '');
}
if (require.main === module) for (const file of ['public/creative-ai/studio.css', 'public/admin/style.css']) {
  const target = path.join(root, file);
  fs.writeFileSync(target, sync(fs.readFileSync(target, 'utf8')));
}
module.exports = { sync, marker, endMarker };
